#!/usr/bin/env node
/**
 * sync-registry.mjs — pin a release of MinBZK/instrument-registry into vendor/.
 *
 *   npm run registry:sync -- v0.1.0
 *
 * Downloads the release tarball from GitHub, replaces
 * vendor/instrument-registry/{assessments,urns.lock.json} with the copy at that
 * tag, and rewrites PROVENANCE.md and pin.json (tag, commit, date). Run `npm run forms:build`
 * afterwards and review the diff in public/forms/: that diff *is* the content
 * change of the new release.
 *
 * The registry is the source of truth for question content. Never hand-edit the
 * vendored YAML: change it upstream, release, sync.
 */
import fs from 'fs'
import os from 'os'
import path from 'path'
import { execFileSync } from 'child_process'
import { fileURLToPath } from 'url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const REPO = 'MinBZK/instrument-registry'
const DEST = path.join(ROOT, 'vendor/instrument-registry')
const MAP = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/registry-map.json'), 'utf8'))

const tag = process.argv[2]
if (!tag || !/^v\d+\.\d+\.\d+$/.test(tag)) {
  console.error('usage: npm run registry:sync -- vX.Y.Z')
  process.exit(1)
}

async function getJson(url) {
  const res = await fetch(url, { headers: { Accept: 'application/vnd.github+json' } })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return res.json()
}

const commit = await getJson(`https://api.github.com/repos/${REPO}/commits/${tag}`)
const sha = commit.sha
const date = commit.commit.committer.date.slice(0, 10)

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'instrument-registry-'))
try {
  const res = await fetch(`https://codeload.github.com/${REPO}/tar.gz/refs/tags/${tag}`)
  if (!res.ok) throw new Error(`tarball ${tag}: HTTP ${res.status}`)
  const tarball = path.join(tmp, 'release.tar.gz')
  fs.writeFileSync(tarball, Buffer.from(await res.arrayBuffer()))
  execFileSync('tar', ['-xzf', tarball, '-C', tmp])
  const [top] = fs.readdirSync(tmp).filter((d) => d.startsWith('instrument-registry-'))
  const src = path.join(tmp, top)

  fs.rmSync(path.join(DEST, 'assessments'), { recursive: true, force: true })
  fs.mkdirSync(path.join(DEST, 'assessments'), { recursive: true })
  for (const f of fs.readdirSync(path.join(src, 'assessments'))) {
    if (f.endsWith('.yaml')) fs.copyFileSync(path.join(src, 'assessments', f), path.join(DEST, 'assessments', f))
  }
  fs.copyFileSync(path.join(src, 'urns.lock.json'), path.join(DEST, 'urns.lock.json'))
  fs.copyFileSync(path.join(src, 'LICENSE'), path.join(DEST, 'LICENSE'))
} finally {
  fs.rmSync(tmp, { recursive: true, force: true })
}

const rows = Object.entries(MAP.forms)
  .map(([id, file]) => `| \`${id}\` | \`assessments/${file}\` |`)
  .join('\n')

fs.writeFileSync(
  path.join(DEST, 'PROVENANCE.md'),
  `# Vendored snapshot — MinBZK/instrument-registry

Pinned copy of the instrument definitions from
[${REPO}](https://github.com/${REPO}), the authoritative source of the question
content of every invulhulp form. Vendored so the build is reproducible and needs
no network. **Do not hand-edit**: change the instrument upstream (pull request on
${REPO}), cut a release, then run

    npm run registry:sync -- <tag>
    npm run forms:build

| Tag | Commit | Commit date |
|-----|--------|-------------|
| \`${tag}\` | \`${sha}\` | ${date} |

Generated by \`scripts/sync-registry.mjs\`. Form id → registry file (from
\`scripts/registry-map.json\`):

| Form id | Registry file |
|---------|---------------|
${rows}
`,
)

// Machine-readable pin, read by .github/workflows/registry-update.yml.
fs.writeFileSync(path.join(DEST, 'pin.json'), JSON.stringify({ repo: REPO, tag, commit: sha, date }, null, 2) + '\n')

console.log(`[registry] ${REPO}@${tag} (${sha.slice(0, 7)}, ${date}) -> vendor/instrument-registry`)
